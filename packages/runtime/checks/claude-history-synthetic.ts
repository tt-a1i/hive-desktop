/** Synthetic native-record fixtures only; this is not a Claude model or team-live test. */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import type { SDKPartialAssistantMessage, SessionMessage } from '@anthropic-ai/claude-agent-sdk';
import { ClaudeProjection } from '../src/agents/claude-projection.js';
import { projectClaudeMessage } from '../src/agents/claude-history.js';
import { claudeCompletionAssistant } from '../src/agents/claude-completion.js';
import type { ClaudeMetadata } from '../src/agents/claude-metadata.js';
const sessionId = randomUUID();
const input = randomUUID();
const firstUuid = randomUUID();
const secondUuid = randomUUID();
const liveUuid = randomUUID();
const metadata: ClaudeMetadata = { version: 1, context: [], completed: [], deliveries: [{ uuid: input, deliveryId: 'A', presentation: { version: 1, origin: 'dispatch', displayText: 'Visible input' } }] };
const projection = new ClaudeProjection(() => metadata);
const source = (type: 'user' | 'assistant', uuid: string, content: unknown[], id = 'api-message'): SessionMessage => ({ type, uuid, session_id: sessionId,
  message: { role: type, id, model: 'synthetic-model-no-inference', content }, parent_tool_use_id: null, parent_agent_id: null });
const event = (value: unknown, uuid = randomUUID()) => ({ type: 'stream_event', uuid, session_id: sessionId, parent_tool_use_id: null, event: value }) as SDKPartialAssistantMessage;
projection.stream(event({ type: 'message_start', message: { id: 'api-message', model: 'synthetic-model-no-inference' } }, liveUuid));
projection.stream(event({ type: 'content_block_start', index: 0, content_block: { type: 'thinking', thinking: '', signature: '' } }));
const thinking = projection.stream(event({ type: 'content_block_delta', index: 0, delta: { type: 'thinking_delta', thinking: 'Inspecting' } }));
assert.equal(thinking?.messageId, liveUuid);
const first = source('assistant', firstUuid, [{ type: 'thinking', thinking: 'Inspecting', signature: '' }]);
assert.equal(projection.put(first)[0]?.id, liveUuid);
projection.stream(event({ type: 'content_block_start', index: 1, content_block: { type: 'text', text: '' } }));
const text = projection.stream(event({ type: 'content_block_delta', index: 1, delta: { type: 'text_delta', text: 'Done' } }));
assert.equal(text?.messageId, liveUuid);
assert.equal(text?.contentIndex, 1);
const second = source('assistant', secondUuid, [{ type: 'text', text: 'Done' }]);
projection.put(second);
projection.stream(event({ type: 'message_stop' }));
const snapshot = projection.snapshot();
assert.deepEqual(snapshot.historyMessageIds, [liveUuid]);
assert.deepEqual(snapshot.history[0]?.content, [{ type: 'thinking', thinking: 'Inspecting', signature: '' }, { type: 'text', text: 'Done' }]);
assert.deepEqual((snapshot.history[0]?.source as { nativeUuids: string[] }).nativeUuids, [firstUuid, secondUuid]);
assert.equal(snapshot.activeMessage, undefined);
// A cumulative completed envelope replaces its earlier block-only version.
projection.put(source('assistant', secondUuid, [{ type: 'thinking', thinking: 'Inspecting', signature: '' }, { type: 'text', text: 'Done' }]));
assert.equal((projection.snapshot().history[0]?.content as unknown[]).length, 2);
const reopened = new ClaudeProjection(() => metadata);
reopened.put(first); reopened.put(second);
assert.deepEqual(reopened.snapshot().historyMessageIds, [firstUuid]);
assert.equal(reopened.hasNativeUuid(secondUuid), true);
const equalBlocks = new ClaudeProjection(() => metadata);
equalBlocks.put(source('assistant', randomUUID(), [{ type: 'text', text: 'OK' }], 'equal-api'));
equalBlocks.put(source('assistant', randomUUID(), [{ type: 'text', text: 'OK' }], 'equal-api'));
assert.deepEqual(equalBlocks.snapshot().history[0]?.content, [{ type: 'text', text: 'OK' }, { type: 'text', text: 'OK' }]);
const delivery = source('user', input, [{ type: 'text', text: 'Full raw input' }]);
const presented = projectClaudeMessage(delivery, metadata)[0]!;
assert.equal(presented.message.role, 'custom');
assert.deepEqual(presented.message.presentation, { ...metadata.deliveries[0]!.presentation, deliveryId: 'A' });
const tool = projectClaudeMessage(source('user', randomUUID(), [{ type: 'tool_result', tool_use_id: 'native-tool-id', content: 'output' }]), metadata)[0]!;
assert.equal(tool.id, 'native-tool-id'); assert.equal(tool.message.role, 'toolResult');
const terminal = { subtype: 'success', is_error: false, uuid: randomUUID(), user_message_uuid: input, terminal_reason: 'completed' };
assert.equal(claudeCompletionAssistant([delivery, first, second], input, new Set([firstUuid, secondUuid]), terminal), secondUuid);
assert.throws(() => claudeCompletionAssistant([delivery, first], input, new Set([secondUuid]), terminal));
assert.throws(() => claudeCompletionAssistant([delivery, source('user', randomUUID(), [{ type: 'text', text: 'B' }]), second], input, new Set([secondUuid]), terminal));
assert.throws(() => claudeCompletionAssistant([delivery, second], input, new Set([secondUuid]), { ...terminal, is_error: true }));
assert.throws(() => claudeCompletionAssistant([delivery, second], input, new Set([secondUuid]), { ...terminal, user_message_uuid: randomUUID() }));
assert.throws(() => claudeCompletionAssistant([delivery, second], input, new Set([secondUuid]), { ...terminal, queued_turn_count: 1 }));
console.log('Synthetic Claude UUID/block projection and exact completion fixtures passed; no model calls');
