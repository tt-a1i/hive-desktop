/** Real Hive HTTP/SQLite, real Git worktrees and paused Pi SDK. No model or native agent calls. */
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, realpath, rename, rm, symlink, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { createDesktopRuntime } from '../src/desktop-runtime.js';
import { createTeamTool } from '../src/team-tool.js';
import type { Chats } from '../src/chats.js';
import type { ChatIndex } from '../src/chat-index.js';
import type { DeliveryQueue } from '../src/delivery-queue.js';
import type { StructuredSessionHandle } from '../src/structured-runtime.js';

const directory = await realpath(await mkdtemp(join(tmpdir(), 'hive-artifact-origins-')));
const repo = join(directory, 'repo'), state = join(directory, 'state'), agent = join(directory, 'pi');
const previous = {PI_CODING_AGENT_DIR: process.env.PI_CODING_AGENT_DIR, PI_OFFLINE: process.env.PI_OFFLINE, GIT_CONFIG_GLOBAL: process.env.GIT_CONFIG_GLOBAL, GIT_CONFIG_NOSYSTEM: process.env.GIT_CONFIG_NOSYSTEM};
let runtime: Awaited<ReturnType<typeof createDesktopRuntime>> | undefined;
const internals = (chats: Chats) => chats as unknown as {index: ChatIndex; live: Map<string, {queue: DeliveryQueue}>};
try {
  await mkdir(repo); await mkdir(agent); await writeFile(join(directory, 'gitconfig'), '');
  process.env.PI_CODING_AGENT_DIR = agent; process.env.PI_OFFLINE = '1';
  process.env.GIT_CONFIG_GLOBAL = join(directory, 'gitconfig'); process.env.GIT_CONFIG_NOSYSTEM = '1';
  const git = (...args: string[]) => execFileSync('git', ['-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', '-c', 'commit.gpgSign=false', ...args], {cwd: repo, encoding: 'utf8', stdio: 'pipe'});
  git('init', '--template='); await writeFile(join(repo, 'same.txt'), 'legacy root'); git('add', '.'); git('commit', '-qm', 'base');
  runtime = await createDesktopRuntime(state, () => {});
  const first = runtime;
  const workspace = await first.hive.request('POST', '/api/workspaces', {path: repo, name: 'Artifact origins', autostart_orchestrator: false}) as {id: string};
  // Before isolated sessions existed, legacy artifacts used the fixed shared root.
  const old = await first.chats.resolveArtifact(workspace.id, {dispatchId: 'old-dispatch', sourceAgentId: 'old-worker', path: 'same.txt'});
  assert.equal(old.path, join(repo, 'same.txt')); assert.equal(old.legacy, true); assert.ok(old.warning);
  const main = await first.chats.create(workspace.id);
  const mainQueue = internals(first.chats).live.get(main.id)!.queue; mainQueue.resume = () => {};
  await mainQueue.pause(); await first.chats.resume(main.id);
  const worker = first.createMember(workspace.id, {name: 'artifact-worker', role: 'coder', backend: 'pi'});
  const a = await first.chats.createRecord(workspace.id, 'pi', {isolation: 'worktree'});
  const b = await first.chats.createRecord(workspace.id, 'pi', {isolation: 'worktree'});
  const rootA = (await first.chats.sessionExecution(a.id)).path, rootB = (await first.chats.sessionExecution(b.id)).path;
  await writeFile(join(rootA, 'same.txt'), 'artifact A'); await writeFile(join(rootB, 'same.txt'), 'artifact B');
  internals(first.chats).index.bind(a.id, worker.id);
  await first.chats.open(a.id);
  const queueA = internals(first.chats).live.get(a.id)!.queue; queueA.resume = () => {}; await queueA.pause();
  const handles = new Map<string, StructuredSessionHandle>();
  const start = first.chats.start.bind(first.chats);
  first.chats.start = async input => { const handle = await start(input); handles.set(input.agentId, handle); return handle; };
  await first.hive.request('POST', `/api/workspaces/${workspace.id}/agents/${encodeURIComponent(worker.id)}/start`);
  const binding = (agentId: string) => ({workspaceId: workspace.id, agentId, token: first.agents.peekAgentToken(agentId)!, hivePort: String(first.hive.port), cwd: repo});
  const command = async (agentId: string, args: string[]) => JSON.parse((await createTeamTool(binding(agentId)).execute('artifact-fixture', {args}, undefined, undefined, undefined as never)).content.map(item => 'text' in item ? item.text : '').join('') || 'null');
  const sent = await command(`${workspace.id}:orchestrator`, ['send', 'artifact-worker', 'Create the artifact in your execution directory']);
  const dispatchId = sent.dispatch_id as string; assert.ok(dispatchId);
  assert.ok(queueA.pending.some(item => item.presentation?.dispatchId === dispatchId));
  const inbox = await command(worker.id, ['messages', '--dispatch', dispatchId]);
  await command(worker.id, ['report', 'Artifact created', '--dispatch', dispatchId, '--seen', String(inbox.required_seen_seq), '--artifact', 'same.txt']);
  const result = await first.chats.resolveArtifact(workspace.id, {dispatchId, sourceAgentId: worker.id, path: 'same.txt'});
  assert.equal(result.path, join(rootA, 'same.txt')); assert.equal(result.sourceSessionId, a.id); assert.equal(await readFile(result.path, 'utf8'), 'artifact A');
  // A sidecar failure rejects acceptance without changing the durable queue.
  const sources = join(state, 'chats', 'dispatch-execution-origins');
  const before = queueA.pending;
  await rename(sources, sources + '.held'); await writeFile(sources, 'blocked source metadata');
  await assert.rejects(handles.get(worker.id)!.deliver('new dispatch', {presentation: {version: 1, origin: 'dispatch', dispatchId: 'write-fault', displayText: 'new dispatch'}}), /DISPATCH_ORIGIN_/);
  assert.deepEqual(queueA.pending, before);
  await rm(sources); await rename(sources + '.held', sources);
  await handles.get(worker.id)!.deliver('new dispatch', {presentation: {version: 1, origin: 'dispatch', dispatchId: 'write-fault', displayText: 'new dispatch'}});
  assert.ok(queueA.pending.some(item => item.presentation?.dispatchId === 'write-fault'));
  const run = first.agents.getActiveRunByAgentId(workspace.id, worker.id)!;
  first.agents.stopAgentRun(run.runId); assert.equal(await first.agents.waitForRunExit(run.runId, 5000), true);
  internals(first.chats).index.bind(b.id, worker.id);
  assert.equal(first.chats.list(workspace.id).find(item => item.id === a.id)!.agentId, undefined);
  await first.chats.open(b.id); const queueB = internals(first.chats).live.get(b.id)!.queue; queueB.resume = () => {}; await queueB.pause();
  await first.hive.request('POST', `/api/workspaces/${workspace.id}/agents/${encodeURIComponent(worker.id)}/start`);
  await assert.rejects(handles.get(worker.id)!.deliver('rebind old dispatch', {presentation: {version: 1, origin: 'dispatch', dispatchId, displayText: 'rebind old dispatch'}}), /DISPATCH_ORIGIN_CONFLICT/);
  assert.equal(queueB.pending.some(item => item.presentation?.dispatchId === dispatchId), false);
  await first.close(); runtime = await createDesktopRuntime(state, () => {});
  const cold = await runtime.chats.resolveArtifact(workspace.id, {dispatchId, sourceAgentId: worker.id, path: 'same.txt'});
  assert.equal(cold.path, join(rootA, 'same.txt')); assert.equal(cold.root, rootA); assert.equal(cold.sourceSessionId, a.id);
  const current = await runtime.chats.createRecord(workspace.id, 'codex');
  internals(runtime.chats).index.bind(current.id, worker.id);
  assert.equal(runtime.chats.inboxDispatchBackend(workspace.id, dispatchId), 'pi');
  assert.equal(runtime.chats.inboxDispatchBackend(workspace.id, 'unknown-dispatch'), undefined);
  assert.equal((await runtime.chats.resolveArtifact(workspace.id, {sourceSessionId: b.id, path: 'same.txt'})).path, join(rootB, 'same.txt'));
  assert.equal((await runtime.chats.resolveArtifact(workspace.id, {sourceSessionId: a.id, path: join(rootA, 'same.txt')})).path, cold.path);
  await assert.rejects(runtime.chats.resolveArtifact(workspace.id, {dispatchId, sourceAgentId: 'wrong', path: 'same.txt'}), /ARTIFACT_SOURCE_MISMATCH/);
  await assert.rejects(runtime.chats.resolveArtifact(workspace.id, {dispatchId, sourceSessionId: b.id, path: 'same.txt'}), /ARTIFACT_SOURCE_MISMATCH/);
  await assert.rejects(runtime.chats.resolveArtifact(workspace.id, {dispatchId: 'missing', sourceAgentId: worker.id, path: 'same.txt'}), /ARTIFACT_SOURCE_UNKNOWN/);
  await assert.rejects(runtime.chats.resolveArtifact(workspace.id, {dispatchId: 'missing', sourceSessionId: a.id, path: 'same.txt'}), /ARTIFACT_SOURCE_UNKNOWN/);
  await assert.rejects(runtime.chats.resolveArtifact(workspace.id, {sourceSessionId: a.id, path: '../same.txt'}), /ARTIFACT_OUTSIDE_SOURCE/);
  await assert.rejects(runtime.chats.resolveArtifact(workspace.id, {sourceSessionId: a.id, path: 'same.txt', root: rootB}), /ARTIFACT_INVALID_REQUEST/);
  const otherRoot = join(directory, 'other'); await mkdir(otherRoot);
  const other = await runtime.hive.request('POST', '/api/workspaces', {path: otherRoot, name: 'Other', autostart_orchestrator: false}) as {id: string};
  assert.equal(runtime.chats.inboxDispatchBackend(other.id, dispatchId), undefined);
  await assert.rejects(runtime.chats.resolveArtifact(other.id, {sourceSessionId: a.id, path: 'same.txt'}), /ARTIFACT_SOURCE_MISMATCH/);
  await symlink(join(repo, 'same.txt'), join(rootA, 'escape.txt'));
  await assert.rejects(runtime.chats.resolveArtifact(workspace.id, {dispatchId, path: 'escape.txt'}), /ARTIFACT_OUTSIDE_SOURCE/);
  await symlink(join(rootA, 'same.txt'), join(rootA, 'inside.txt'));
  assert.equal((await runtime.chats.resolveArtifact(workspace.id, {dispatchId, path: 'inside.txt'})).path, cold.path);
  await assert.rejects(runtime.chats.resolveArtifact(workspace.id, {dispatchId, path: '.'}), /ARTIFACT_(OUTSIDE_SOURCE|NOT_FILE)/);
  await rename(rootA, rootA + '.missing');
  await assert.rejects(runtime.chats.resolveArtifact(workspace.id, {dispatchId, sourceAgentId: worker.id, path: 'same.txt'}), /ARTIFACT_SOURCE_UNAVAILABLE/);
  assert.equal(await readFile(join(rootB, 'same.txt'), 'utf8'), 'artifact B');
  await rename(rootA + '.missing', rootA);
  console.log('ARTIFACT_EXECUTION_ORIGINS_OK: real Hive dispatch/report, same-worker A→B rebinding, cold provenance, direct tools, source mismatches, private sidecar write failure/queue retention, canonical boundaries and missing-source refusal. No models.');
} finally {
  await runtime?.close();
  for (const [key, value] of Object.entries(previous)) { if (value === undefined) delete process.env[key]; else process.env[key] = value; }
  await rm(directory, {recursive: true, force: true, maxRetries: 5});
}
