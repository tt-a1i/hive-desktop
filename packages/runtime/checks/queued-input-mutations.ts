import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdirSync, mkdtempSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DeliveryQueue } from '../src/delivery-queue.js';
const directory = mkdtempSync(join(tmpdir(), 'hive-queue-mutations-'));
const path = (id: string) => join(directory, createHash('sha256').update(id).digest('hex') + '.json');
const user = { version: 1 as const, origin: 'user' as const, displayText: 'original', sourceText: 'source', attachments: [{ id: 'a', workspaceId: 'w', name: 'file', mimeType: 'image/png', size: 5 }] };
try {
 let release!: () => void, started!: () => void;
 const blocked = new Promise<void>(r => { release = r; });
 const entered = new Promise<void>(r => { started = r; });
 let events = 0; const executed: string[] = [];
 const q = new DeliveryQueue({ directory, sessionId: 'main', completedIds: () => [], onError: e => { throw e; },
  onState: () => { events++; }, execute: async item => { executed.push(item.text); if (item.text === 'head') { started(); await blocked; } } });
 await q.enqueue('head', true, user); await entered;
 await q.enqueue('old', true, user);
 await q.enqueue('report', true, { version: 1, origin: 'report', displayText: 'report' });
 const [head, target, report] = q.pending;
 assert.throws(() => q.cancelPendingUserInput(head!.id), /processing/);
 assert.throws(() => q.cancelPendingUserInput(report!.id), /not-user/);
 const replacement = { ...target!, text: 'new', presentation: { ...target!.presentation!, displayText: 'edited', sourceText: 'edited source' } };
 assert.throws(() => q.editPendingUserInput(target!.id, { ...replacement, presentation: { ...replacement.presentation, attachments: [] } }), /metadata/);
 const count = events; q.editPendingUserInput(target!.id, replacement);
 assert.equal(events, count + 1); assert.equal(q.pending[1]!.presentation!.sourceText, 'edited source');
 const before = readFileSync(path('main'), 'utf8');
 renameSync(path('main'), path('main') + '.held'); mkdirSync(path('main'));
 assert.throws(() => q.cancelPendingUserInput(target!.id));
 assert.equal(q.pending[1]!.text, 'new');
 rmSync(path('main'), { recursive: true }); renameSync(path('main') + '.held', path('main'));
 assert.equal(readFileSync(path('main'), 'utf8'), before);
 q.cancelPendingUserInput(target!.id); release(); await q.idle();
 assert.deepEqual(executed, ['head', 'report']);
 const delivered: string[] = [];
 const paused = new DeliveryQueue({ directory, sessionId: 'edited', startPaused: true, completedIds: () => [], onError: e => { throw e; }, execute: async item => { delivered.push(item.text); } });
 await paused.enqueue('before', true, user);
 const edit = paused.pending[0]!; paused.editPendingUserInput(edit.id, { ...edit, text: 'after', presentation: { ...edit.presentation!, displayText: 'after' } });
 const editedCold = new DeliveryQueue({ directory, sessionId: 'edited', startPaused: true, completedIds: () => [], onError: e => { throw e; }, execute: async item => { delivered.push(item.text); } });
 editedCold.resume(); await editedCold.idle(); assert.deepEqual(delivered, ['after']);
 // Simulate a crash after spool tombstone and before the authoritative commit.
 const stopped: string[] = [];
 const tx = new DeliveryQueue({ directory, sessionId: 'tx', startPaused: true, completedIds: () => [], onError: e => { throw e; }, execute: async item => { stopped.push(item.text); } });
 await tx.enqueue('one', true, user); await tx.enqueue('two', true, user);
 const old = tx.pending[0]!; tx.cancelPendingUserInput(old.id, { retain: true });
 const recovery = new DeliveryQueue({ directory, sessionId: 'tx', startPaused: true, completedIds: () => [], onError: e => { throw e; }, execute: async item => { stopped.push(item.text); } });
 assert.equal(recovery.pendingUserInputs[0]!.reason, 'canceled');
 recovery.resume(); await recovery.idle(); assert.deepEqual(stopped, []);
 recovery.reconcilePendingUserInput(old.id, old); await recovery.idle(); assert.deepEqual(stopped, ['one', 'two']);
 // Simulate the authoritative cancellation having committed before spool cleanup.
 const tx2 = new DeliveryQueue({ directory, sessionId: 'tx2', startPaused: true, completedIds: () => [], onError: e => { throw e; }, execute: async item => { stopped.push(item.text); } });
 await tx2.enqueue('remove', true, user); await tx2.enqueue('keep', true, user);
 const removed = tx2.pending[0]!; tx2.cancelPendingUserInput(removed.id, { retain: true });
 const recovery2 = new DeliveryQueue({ directory, sessionId: 'tx2', startPaused: true, completedIds: () => [], onError: e => { throw e; }, execute: async item => { stopped.push(item.text); } });
 assert.throws(() => recovery2.reconcilePendingUserInput(removed.id, { ...removed, presentation: { ...removed.presentation!, attachments: [] } }), /metadata/);
 recovery2.reconcilePendingUserInput(removed.id, null); recovery2.resume(); await recovery2.idle();
 assert.deepEqual(stopped, ['one', 'two', 'keep']);
 const failed = new DeliveryQueue({ directory, sessionId: 'failed', completedIds: () => [], onError: () => {}, execute: async () => { throw Error('failed'); } });
 await failed.enqueue('failed', true, user); await failed.idle();
 const cold = new DeliveryQueue({ directory, sessionId: 'failed', startPaused: true, completedIds: () => [], onError: () => {}, execute: async () => {} });
 assert.throws(() => cold.cancelPendingUserInput(failed.pending[0]!.id), /attempted/);
 assert.equal(cold.pendingUserInputs[0]!.editable, false);
 writeFileSync(path('legacy'), JSON.stringify([{ id: 'head', text: 'x', triggerTurn: true, presentation: user }, { id: 'tail', text: 'y', triggerTurn: true, presentation: user }]));
 const legacy = new DeliveryQueue({ directory, sessionId: 'legacy', startPaused: true, completedIds: () => [], onError: () => {}, execute: async () => {} });
 assert.throws(() => legacy.cancelPendingUserInput('head'), /attempted/);
 legacy.cancelPendingUserInput('tail');
 const done = new DeliveryQueue({ directory, sessionId: 'done', startPaused: true, completedIds: () => ['head'], onError: () => {}, execute: async () => {} });
 writeFileSync(path('done'), JSON.stringify([{ id: 'head', text: 'x', triggerTurn: true, queueState: 'pending', presentation: user }]));
 const coldDone = new DeliveryQueue({ directory, sessionId: 'done', startPaused: true, completedIds: () => ['head'], onError: () => {}, execute: async () => {} });
 assert.throws(() => coldDone.cancelPendingUserInput('head'), /completed/);
 void done;
 console.log('QUEUED_INPUT_MUTATIONS_OK');
} finally { rmSync(directory, { recursive: true, force: true }); }
